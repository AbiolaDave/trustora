import mongoose, { Schema, type InferSchemaType, type Model } from "mongoose";

const paymentSchema = new Schema(
  {
    booking: { type: Schema.Types.ObjectId, ref: "Booking", required: true, index: true },
    customer: { type: Schema.Types.ObjectId, ref: "User", required: true, index: true },
    provider: { type: String, enum: ["paystack", "mock"], required: true },
    reference: { type: String, required: true, unique: true }, // generated by US and sent to the provider
    amountKobo: { type: Number, required: true },
    currency: { type: String, enum: ["NGN"], default: "NGN" },
    status: { type: String, enum: ["initialized", "success", "failed", "abandoned"], default: "initialized", index: true },
    paidAt: Date,
    channel: String,
    providerFeeKobo: Number, // only when the provider reports it
    breakdown: { serviceChargeKobo: Number, travelKobo: Number, customerFeeKobo: Number, commissionKobo: Number, artisanDueKobo: Number },
    refunds: [{ amountKobo: Number, providerRef: String, status: { type: String, enum: ["pending", "processed", "failed"] }, reason: String, at: Date }],
    /** Provider event ids already applied, so duplicate webhook deliveries are harmless. */
    processedEventIds: [String],
    // Never store card numbers, CVVs or secret keys here. Only provider-safe metadata.
  },
  { timestamps: true },
);

export type PaymentDoc = InferSchemaType<typeof paymentSchema> & { _id: mongoose.Types.ObjectId };
export const Payment: Model<PaymentDoc> = (mongoose.models.Payment as Model<PaymentDoc>) || mongoose.model<PaymentDoc>("Payment", paymentSchema);
